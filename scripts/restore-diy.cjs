const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const path = 'src/app/page.tsx';
const bytes = fs.readFileSync(path);
assert.equal(crypto.createHash('sha1').update(Buffer.from('blob ' + bytes.length + '\0')).update(bytes).digest('hex'), '1e28c5a126e9d843f8969a851c7a0e463ea00c65', 'Unexpected page version; refusing overwrite');
let text = bytes.toString('utf8');
function replaceOnce(from, to) { assert.equal(text.split(from).length - 1, 1, 'Expected unique anchor: ' + from); text = text.replace(from, to); }
replaceOnce('type Item = {', 'type Item = {\n  id?: string;');
replaceOnce('  const { visibleItems, panel: vehicleFilterPanel } = useVehicleMaterialFilter(items);\n', '');
replaceOnce("  const [selectedModel, setSelectedModel] = useState('Wszystkie');", "  const materialScope = tab === 'diy' || tab === 'schematy' ? ['Porada'] : tab === 'kody' ? ['Kod błędu'] : tab === 'usterki' ? ['Usterka'] : undefined;\n  const { visibleItems, panel: vehicleFilterPanel } = useVehicleMaterialFilter(items, materialScope);\n  const [selectedModel, setSelectedModel] = useState('Wszystkie');");
const start = text.indexOf("{tab === 'diy' && (");
const end = text.indexOf("{tab === 'schematy' && (", start);
assert(start >= 0 && end > start);
const segment = text.slice(start, end);
const guards = [...segment.matchAll(/\{tab === 'diy_?content' && \(/g)];
assert.equal(guards.length, 1, 'Expected one orphaned DIY content block');
const split = guards[0].index;
const videos = segment.slice(0, split);
let instructions = segment.slice(split).replace(/tab === 'diy_?content'/, "tab === 'diy'");
const paragraph = '<p className="text-neutral-300 text-sm whitespace-pre-line">{t.Rozwiązanie}</p>';
assert.equal(instructions.split(paragraph).length - 1, 1);
instructions = instructions.replace(paragraph, '<VehicleMatchBadge item={t} />\n                      {t.Opis && <p className="mb-3 text-neutral-400 text-sm whitespace-pre-line">{t.Opis}</p>}\n                      ' + paragraph + '\n                      {t.id && <a className="mt-3 inline-block text-sm text-amber-400 underline" href={\'/baza/\' + encodeURIComponent(t.id)}>Otwórz pełną instrukcję z ilustracjami</a>}');
assert(instructions.includes('getTipImage(t.Nazwa)'));
assert(instructions.includes('setLightbox(tipImg)'));
text = text.slice(0, start) + instructions + videos + text.slice(end);
assert(!/tab === 'diy_?content'/.test(text));
for (const image of ['diy-4l60e-pan-pl.jpg', 'diy-intake-pl.jpg', 'diy-np231-pl.jpg', 'diy-brakes-pl.jpg']) assert(fs.existsSync('public/' + image), 'Missing graphic: ' + image);
fs.writeFileSync(path, text);
