const fs = require('node:fs');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const path = 'src/app/page.tsx';
const bytes = fs.readFileSync(path);
let source = bytes.toString('utf8');
const usage = '<VinHistorySummary key={vinResult.VIN} vin={vinResult.VIN} />';
const imported = "import VinHistorySummary from './VinHistorySummary';";
if (source.includes(usage) && source.includes(imported) && !source.includes('Lot #12345') && !source.includes('Math.random() > 0.7')) {
  console.log('VIN integration already present');
  process.exit(0);
}
const sha = crypto.createHash('sha1').update(Buffer.from('blob ' + bytes.length + '\0')).update(bytes).digest('hex');
assert.equal(sha, 'aba8005190d342d575525274e90e486c1c802188', 'Unexpected source version; refusing to overwrite');
assert.ok(fs.existsSync('src/app/VinHistorySummary.tsx'), 'Missing VIN summary component');
const anchor = "import { useState, useEffect, useMemo } from 'react';";
assert.ok(source.includes(anchor));
source = source.replace(anchor, anchor + '\n' + imported);
let start = source.indexOf('// Check for warning conditions');
let end = source.indexOf('if (hasWarning) playGong();', start);
assert.ok(start >= 0 && end > start);
source = source.slice(0, start) + 'setVinWarning(false);' + source.slice(end + 'if (hasWarning) playGong();'.length);
const vinSection = source.indexOf("{tab === 'vin'");
start = source.indexOf('                <div className="flex items-center justify-between mb-3">', vinSection);
end = source.indexOf('                <h4 className="font-semibold text-amber-400 mb-2">POWIĄZANE INFORMACJE', start);
assert.ok(vinSection >= 0 && start > vinSection && end > start);
source = source.slice(0, start) + '                <h3 className="font-semibold text-amber-400 mb-3">HISTORIA I ZDJĘCIA TEGO VIN</h3>\n                ' + usage + '\n\n' + source.slice(end);
assert.ok(!source.includes('Lot #12345') && !source.includes('Math.random() > 0.7'));
assert.equal(source.split(usage).length - 1, 1);
fs.writeFileSync(path, source);
console.log('VIN history integrated into existing decoder');
